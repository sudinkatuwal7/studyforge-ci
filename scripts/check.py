"""Run StudyForge checks on Windows or Linux without touching development data."""

import argparse
from contextlib import contextmanager
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
SUITES = {
    "all": ["backend/apps", "backend/tests"],
    "identity-courses": ["backend/tests/users", "backend/apps/courses"],
    "documents": ["backend/tests/documents", "backend/apps/documents"],
    "ai-learning": ["backend/apps/processing", "backend/apps/knowledge", "backend/apps/notes", "backend/apps/quizzes"],
}


def test_environment():
    env = os.environ.copy()
    for key in (
        "OPENAI_API_KEY", "OPENAI_ADMIN_KEY", "GEMINI_API_KEY", "GOOGLE_API_KEY",
        "GOOGLE_APPLICATION_CREDENTIALS", "GOOGLE_GENAI_USE_VERTEXAI",
        "PYTEST_ADDOPTS", "PYTEST_PLUGINS",
    ):
        env.pop(key, None)
    env.update(
        NOTES_LLM_BACKEND="fake", QUIZ_LLM_BACKEND="fake", DJANGO_SETTINGS_MODULE="config.test_settings",
        DATABASE_ENGINE="postgresql", EMBEDDING_DIMENSION="768",
        EMBEDDING_BATCH_SIZE="16", EMBEDDING_MODEL="gemini-embedding-2",
        VITE_API_BASE_URL="http://api.test/api/v1",
    )
    return env


def run(label, args, env, cwd=ROOT):
    print(f"\n[check] {label}", flush=True)
    result = subprocess.run(args, cwd=cwd, env=env, check=False)
    print(f"[check] {label}: {'PASS' if result.returncode == 0 else 'FAIL'}", flush=True)
    return result.returncode


@contextmanager
def database(env, mode):
    """Create fresh databases; never reuse or migrate the development database."""
    import psycopg
    from psycopg import sql

    name = f"studyforge_ci_{uuid4().hex[:12]}"
    container = None
    created = False
    params = {
        "host": "127.0.0.1", "port": "5432",
        "user": "studyforge_ci", "password": "disposable-ci-only",
    }
    try:
        if mode == "docker":
            docker = shutil.which("docker")
            if not docker:
                raise RuntimeError("Docker is required. Start Docker Desktop (Linux containers).")
            container_name = name.replace("_", "-")
            subprocess.run([
                docker, "run", "--detach", "--rm", "--name", container_name,
                "--publish", "127.0.0.1::5432", "--tmpfs", "/var/lib/postgresql/data",
                "--env", "POSTGRES_USER=studyforge_ci",
                "--env", "POSTGRES_PASSWORD=disposable-ci-only",
                "--env", "POSTGRES_DB=postgres", "pgvector/pgvector:pg16",
            ], check=True, stdout=subprocess.DEVNULL)
            container = container_name
            binding = subprocess.check_output(
                [docker, "port", container, "5432/tcp"], text=True
            ).strip()
            params["port"] = binding.rsplit(":", 1)[1]
        else:
            # Separate variables prevent accidental use of application POSTGRES_* values.
            params.update(
                host=os.environ.get("CI_POSTGRES_HOST", "127.0.0.1"),
                port=os.environ.get("CI_POSTGRES_PORT", "5432"),
                user=os.environ.get("CI_POSTGRES_USER", "studyforge_ci"),
                password=os.environ.get("CI_POSTGRES_PASSWORD", ""),
            )
            if not params["password"]:
                raise RuntimeError("Service mode requires CI_POSTGRES_PASSWORD for a dedicated test server.")

        for attempt in range(30):
            try:
                with psycopg.connect(dbname="postgres", connect_timeout=2, **params):
                    pass
                break
            except psycopg.OperationalError:
                if attempt == 29:
                    raise RuntimeError("Test PostgreSQL is unavailable; check Docker or CI_POSTGRES_*.") from None
                time.sleep(1)

        with psycopg.connect(dbname="postgres", autocommit=True, **params) as conn:
            conn.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
            created = True
        env.update(
            STUDYFORGE_TEST_DB_NAME=name,
            STUDYFORGE_TEST_DB_HOST=params["host"],
            STUDYFORGE_TEST_DB_PORT=params["port"],
            STUDYFORGE_TEST_DB_USER=params["user"],
            STUDYFORGE_TEST_DB_PASSWORD=params["password"],
        )
        yield
    finally:
        if container:
            # This exact container was created above, has --rm, and has no persistent volume.
            subprocess.run([docker, "stop", container], check=True, stdout=subprocess.DEVNULL)
        elif created:
            # Only names generated by this invocation are eligible for cleanup.
            with psycopg.connect(dbname="postgres", autocommit=True, **params) as conn:
                for owned_name in (f"test_{name}", name):
                    conn.execute(sql.SQL("DROP DATABASE IF EXISTS {}").format(sql.Identifier(owned_name)))


def backend(env, mode, suite):
    if sys.version_info[:2] != (3, 12):
        raise RuntimeError("Backend checks require Python 3.12; activate backend/venv first.")
    report = ROOT / "test-results" / f"backend-{suite}.xml"
    report.parent.mkdir(exist_ok=True)
    report.unlink(missing_ok=True)  # Do not present an old report after a failed setup.
    with tempfile.TemporaryDirectory(prefix="studyforge-tests-") as media:
        env["STUDYFORGE_TEST_MEDIA_ROOT"] = media
        with database(env, mode):
            commands = [
                ("Django system checks", ["backend/manage.py", "check"]),
                ("Migration drift", ["backend/manage.py", "makemigrations", "--check", "--dry-run"]),
                ("Fresh database migrations", ["backend/manage.py", "migrate", "--noinput"]),
                (f"Backend tests ({suite})", [
                    "-m", "pytest", *SUITES[suite], "-q", "-ra",
                    "-o", f"cache_dir={Path(media) / 'pytest-cache'}",
                    f"--basetemp={Path(media) / 'pytest'}", f"--junitxml={report}",
                ]),
            ]
            return [run(label, [sys.executable, *args], env) for label, args in commands]


def frontend(env):
    node = shutil.which("node")
    npm = shutil.which("npm.cmd" if os.name == "nt" else "npm")
    if not node or not npm:
        raise RuntimeError("Install Node 24.19.0 and run npm ci in frontend first.")
    version = subprocess.check_output([node, "--version"], text=True).strip()
    parts = tuple(int(part) for part in version.removeprefix("v").split("."))
    if parts[0] != 24 or parts < (24, 15, 0):
        raise RuntimeError(f"Node 24 >=24.15.0 required by the lockfile; found {version}.")
    report = ROOT / "frontend" / "test-results" / "frontend.xml"
    report.parent.mkdir(exist_ok=True)
    report.unlink(missing_ok=True)
    return [
        run(label, [npm, "run", script], env, ROOT / "frontend")
        for label, script in (("Oxlint", "lint"), ("Frontend tests", "test:ci"), ("TypeScript and build", "build"))
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--component", choices=("all", "backend", "frontend"), default="all")
    parser.add_argument("--suite", choices=SUITES, default="all", help="Backend domain subset; CI always uses all.")
    parser.add_argument("--database", choices=("docker", "service"), default="docker")
    args = parser.parse_args()
    env = test_environment()
    results = []
    try:
        if args.component in ("all", "backend"):
            results.extend(backend(env, args.database, args.suite))
        if args.component in ("all", "frontend"):
            results.extend(frontend(env))
    except (RuntimeError, ImportError, OSError, subprocess.SubprocessError) as exc:
        print(f"[check] Setup/cleanup failed: {exc}", file=sys.stderr)
        return 1
    return int(any(results))


if __name__ == "__main__":
    raise SystemExit(main())
